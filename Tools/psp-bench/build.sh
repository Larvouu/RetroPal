#!/bin/bash
# Build the psp-bench host harness against PPSSPP's libretro core.
#
# Usage: Tools/psp-bench/build.sh <ppsspp-build-dir> <out-dir> [<lzfse-src-dir>]
#
#   <ppsspp-build-dir>  a CMake build of PPSSPP with -DLIBRETRO=ON for this
#                       machine (its lib/ holds the static libraries and
#                       CMakeFiles/ppsspp_libretro.dir the port's objects)
#   <out-dir>           where the core's shared object and the harness go
#   <lzfse-src-dir>     the reference LZFSE (git clone github.com/lzfse/lzfse),
#                       needed by the capture and verify modes: they write and
#                       read slot files with PSPBridge's own format code, the
#                       lines of PSPBridge.mm from "#pragma mark - Save-state
#                       files" to PSP_STATE_FORMAT_END, cut out here unchanged,
#                       over shim/compression.h. Without it those two modes
#                       stop with a message and the others build as before.
#
# The core is re-linked here into one shared object that exports ONLY the
# retro_* entry points (a version script), the host's equivalent of the
# phone's pre-linked object: PPSSPP carries its own Vulkan loader pointers,
# zstd, rcheevos, glslang and SPIRV-Cross, and none of them may meet the
# system's libvulkan here, or the app's own copies on the phone. The shared
# object CMake builds exports ~24,000 symbols.
#
# The Vulkan half is the app's own N64VulkanFrontend.mm, compiled unchanged
# but for one line (its log handle is made through a block, which only clang
# compiles), exactly as Tools/n64-bench does. Runs on lavapipe (Mesa's CPU
# Vulkan): VK_ICD_FILENAMES=/usr/share/vulkan/icd.d/lvp_icd.json
#
# Needs g++, the Vulkan loader (libvulkan.so.1) and the libraries PPSSPP's
# Linux build links (libGL, libEGL, zlib).

set -euo pipefail

BUILD="$(cd "$1" && pwd)"
OUT="$2"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
APP_BRIDGE="$ROOT/EmulateurGBA/EmulatorCore/Bridge"
PPSSPP="$(cd "$BUILD/.." && pwd)"

mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"

# The link line CMake used for ppsspp_libretro.so, reused with our export list.
NINJA_LINE="$(ninja -C "$BUILD" -t commands lib/ppsspp_libretro.so 2>/dev/null | tail -1)"
[ -n "$NINJA_LINE" ] || { echo "cannot read the core's link line from $BUILD"; exit 1; }

echo "{ global: retro_*; local: *; };" > "$OUT/exports.map"
LINE="${NINJA_LINE/-o lib\/ppsspp_libretro.so/-o $OUT/libpspcore.so}"
LINE="${LINE/-Wl,-soname,ppsspp_libretro.so/-Wl,-soname,libpspcore.so}"
LINE="${LINE/-Wl,-Bsymbolic/-Wl,-Bsymbolic -Wl,--version-script=$OUT/exports.map}"
(cd "$BUILD" && eval "$LINE")

LEAKED="$(nm -D --defined-only "$OUT/libpspcore.so" | awk '{print $3}' | grep -v '^retro_' | grep -v '^_\(init\|fini\)$' || true)"
[ -z "$LEAKED" ] || { echo "the core exports more than retro_*:"; echo "$LEAKED" | head; exit 1; }
echo "core: $(nm -D --defined-only "$OUT/libpspcore.so" | grep -c ' retro_') retro_* exports, nothing else"

sed 's/dispatch_once(&once, ^{ log = os_log_create("com.retropal.emulateurgba", "n64-vulkan"); });/log = os_log_create("com.retropal.emulateurgba", "n64-vulkan"); (void)once;/' \
    "$APP_BRIDGE/N64VulkanFrontend.mm" > "$OUT/N64VulkanFrontend.cpp"
grep -q 'dispatch_once(&once, \^' "$OUT/N64VulkanFrontend.cpp" && { echo "the frontend's log line changed; update this script"; exit 1; }

# The bridge's state format, cut out of PSPBridge.mm unchanged.
FORMAT_START='#pragma mark - Save-state files'
FORMAT_END='// PSP_STATE_FORMAT_END'
grep -qF "$FORMAT_START" "$APP_BRIDGE/PSPBridge.mm" && grep -qF "$FORMAT_END" "$APP_BRIDGE/PSPBridge.mm" \
    || { echo "PSPBridge.mm's state-format markers moved; update this script"; exit 1; }
LZFSE_OBJS=()
if [ -n "${3:-}" ]; then
    LZFSE="$(cd "$3" && pwd)"
    {
        echo '// Generated by Tools/psp-bench/build.sh from PSPBridge.mm. Do not edit.'
        echo '#include <compression.h>'
        echo '#include <cstdint>'
        echo '#include <cstring>'
        echo '#include <vector>'
        echo 'namespace {'
        awk -v s="$FORMAT_START" -v e="$FORMAT_END" 'index($0, s) == 1 {on = 1} on {print} index($0, e) == 1 {exit}' \
            "$APP_BRIDGE/PSPBridge.mm"
        echo '}  // namespace'
    } > "$OUT/PSPStateFormat.inc"
    for c in "$LZFSE"/src/lzfse_{decode,decode_base,encode,encode_base,fse}.c "$LZFSE"/src/lzvn_{decode_base,encode_base}.c; do
        o="$OUT/$(basename "$c" .c).o"
        gcc -O2 -c "$c" -o "$o"
        LZFSE_OBJS+=("$o")
    done
    FORMAT_INCLUDES=(-I"$HERE/shim" -I"$LZFSE/src")
else
    {
        echo '// Generated by Tools/psp-bench/build.sh: built without LZFSE.'
        echo '#define PSP_BENCH_NO_STATE_FORMAT 1'
        echo '#include <cstdint>'
        echo '#include <vector>'
        echo 'namespace {'
        echo 'size_t PSPUsedLength(const uint8_t *, size_t length) { return length; }'
        echo 'bool PSPStateFormatPack(const uint8_t *, size_t, std::vector<uint8_t> &) { return false; }'
        echo 'bool PSPStateFormatUnpack(const uint8_t *, size_t, std::vector<uint8_t> &) { return false; }'
        echo '}  // namespace'
    } > "$OUT/PSPStateFormat.inc"
    FORMAT_INCLUDES=()
fi

g++ -std=c++17 -O2 -g \
    -I"$ROOT/Tools/n64-bench/shim" -I"$APP_BRIDGE" -I"$OUT" "${FORMAT_INCLUDES[@]}" \
    -I"$PPSSPP/libretro/libretro-common/include" -I"$PPSSPP/ext/vulkan" \
    "$OUT/N64VulkanFrontend.cpp" "$HERE/psp-bench.cpp" "${LZFSE_OBJS[@]}" \
    -L"$OUT" -lpspcore -Wl,-rpath,"$OUT" \
    -l:libvulkan.so.1 -lstdc++ -lm -lpthread -ldl \
    -o "$OUT/psp-bench"

echo "$OUT/psp-bench"
