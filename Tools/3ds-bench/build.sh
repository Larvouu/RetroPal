#!/bin/bash
# Build the 3ds-bench host harness against the 3DS core as the app links it.
#
# Usage: Tools/3ds-bench/build.sh <out-dir> [<lzfse-src-dir>]
#
#   <lzfse-src-dir>  the reference LZFSE (git clone github.com/lzfse/lzfse),
#                    needed by the stateformat mode: it writes and reads slot
#                    files with CTRBridge's own format code, the lines of
#                    CTRBridge.mm from "#pragma mark - Save-state files" to
#                    CTR_STATE_FORMAT_END, cut out here unchanged, over
#                    Tools/psp-bench/shim/compression.h. Without it that mode
#                    stops with a message.
#
# Takes Vendor/azahar-ios/lib/libctr-core-host.so, made by
#   HOST=1 Vendor/azahar-ios/build.sh
# which is the phone's library built for this machine: the same sources, the
# same options (no console keys), the same renaming to ctr_retro_* and the same
# objects, linked into one shared object exporting only those names (ELF cannot
# hide C++ symbols in a relocatable object the way ld64 does; build.sh says
# why). The harness includes
# ctr_symbols.h before libretro.h, as the bridge will, so it calls the renamed
# entry points.
#
# The one difference from the phone, on purpose: the host build does not define
# IOS, so the core keeps its JIT option and the harness can measure FastInterp,
# DynCom and the JIT side by side (--cpu). On the phone IOS is defined and the
# JIT is not even an option.
#
# The Vulkan half is the app's own N64VulkanFrontend.mm, compiled unchanged
# but for one line (its log handle is made through a block, which only clang
# compiles), exactly as Tools/n64-bench and Tools/psp-bench do. Runs on
# lavapipe (Mesa's CPU Vulkan):
#   VK_ICD_FILENAMES=/usr/share/vulkan/icd.d/lvp_icd.json
#
# Needs g++ and the Vulkan loader (libvulkan.so.1).

set -euo pipefail

OUT="$1"
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
APP_BRIDGE="$ROOT/EmulateurGBA/EmulatorCore/Bridge"
AZAHAR="$ROOT/Vendor/azahar"
CTR_IOS="$ROOT/Vendor/azahar-ios"
CORE_LIB="$CTR_IOS/lib/libctr-core-host.so"

[ -f "$CORE_LIB" ] || { echo "$CORE_LIB is missing: run HOST=1 Vendor/azahar-ios/build.sh first"; exit 1; }
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"

sed 's/dispatch_once(&once, ^{ log = os_log_create("com.retropal.emulateurgba", "n64-vulkan"); });/log = os_log_create("com.retropal.emulateurgba", "n64-vulkan"); (void)once;/' \
    "$APP_BRIDGE/N64VulkanFrontend.mm" > "$OUT/N64VulkanFrontend.cpp"
grep -q 'dispatch_once(&once, \^' "$OUT/N64VulkanFrontend.cpp" && { echo "the frontend's log line changed; update this script"; exit 1; }

# CTRBridge.mm's state format, cut out unchanged.
FORMAT_START='#pragma mark - Save-state files'
FORMAT_END='// CTR_STATE_FORMAT_END'
grep -qF "$FORMAT_START" "$APP_BRIDGE/CTRBridge.mm" && grep -qF "$FORMAT_END" "$APP_BRIDGE/CTRBridge.mm" \
    || { echo "CTRBridge.mm's state-format markers moved; update this script"; exit 1; }
LZFSE_OBJS=()
FORMAT_INCLUDES=()
if [ -n "${2:-}" ]; then
    LZFSE="$(cd "$2" && pwd)"
    {
        echo '// Generated by Tools/3ds-bench/build.sh from CTRBridge.mm. Do not edit.'
        echo '#include <compression.h>'
        echo '#include <cstdint>'
        echo '#include <cstring>'
        echo '#include <vector>'
        echo 'namespace {'
        awk -v s="$FORMAT_START" -v e="$FORMAT_END" 'index($0, s) == 1 {on = 1} on {print} index($0, e) == 1 {exit}' \
            "$APP_BRIDGE/CTRBridge.mm"
        echo '}  // namespace'
    } > "$OUT/CTRStateFormat.inc"
    for c in "$LZFSE"/src/lzfse_{decode,decode_base,encode,encode_base,fse}.c "$LZFSE"/src/lzvn_{decode_base,encode_base}.c; do
        o="$OUT/$(basename "$c" .c).o"
        gcc -O2 -c "$c" -o "$o"
        LZFSE_OBJS+=("$o")
    done
    FORMAT_INCLUDES=(-I"$ROOT/Tools/psp-bench/shim" -I"$LZFSE/src")
else
    {
        echo '// Generated by Tools/3ds-bench/build.sh: built without LZFSE.'
        echo '#include <cstdint>'
        echo '#include <vector>'
        echo 'namespace {'
        echo 'bool CTRStateFormatPack(const uint8_t *, size_t, std::vector<uint8_t> &) { return false; }'
        echo 'bool CTRStateFormatUnpack(const uint8_t *, size_t, std::vector<uint8_t> &) { return false; }'
        echo '}  // namespace'
    } > "$OUT/CTRStateFormat.inc"
fi

# CTRBridge.mm's rewind data work (recording and applying a step), cut out
# unchanged so the rewindbridge mode runs that very text against the core.
REWIND_START='#pragma mark - Rewind data'
REWIND_END='// CTR_REWIND_DATA_END'
grep -qF "$REWIND_START" "$APP_BRIDGE/CTRBridge.mm" && grep -qF "$REWIND_END" "$APP_BRIDGE/CTRBridge.mm" \
    || { echo "CTRBridge.mm's rewind-data markers moved; update this script"; exit 1; }
{
    echo '// Generated by Tools/3ds-bench/build.sh from CTRBridge.mm. Do not edit.'
    echo '#include <algorithm>'
    echo '#include <atomic>'
    echo '#include <cstdint>'
    echo '#include <cstdlib>'
    echo '#include <cstring>'
    echo '#include <vector>'
    echo '#include <compression.h>'
    awk -v s="$REWIND_START" -v e="$REWIND_END" 'index($0, s) == 1 {on = 1} on {print} index($0, e) == 1 {exit}' \
        "$APP_BRIDGE/CTRBridge.mm"
} > "$OUT/CTRRewindData.inc"

# The frontend is compiled WITHOUT the renaming (it calls no retro_* entry
# point); the harness WITH it.
g++ -std=c++17 -O2 -g -c \
    -I"$ROOT/Tools/n64-bench/shim" -I"$APP_BRIDGE" \
    -I"$AZAHAR/externals/libretro-common/libretro-common/include" \
    -I"$AZAHAR/externals/vulkan-headers/include" \
    "$OUT/N64VulkanFrontend.cpp" -o "$OUT/N64VulkanFrontend.o"
# The rewind mode reads a state's payload, which the core compresses with zstd:
# Azahar's own zstd, the static library its host build made.
ZSTD_LIB="$CTR_IOS/build/cmake-host/externals/zstd/build/cmake/lib/libzstd.a"
[ -f "$ZSTD_LIB" ] || { echo "ERROR: $ZSTD_LIB is missing: run HOST=1 Vendor/azahar-ios/build.sh first."; exit 1; }
g++ -std=c++17 -O2 -g -c -include "$CTR_IOS/ctr_symbols.h" \
    -I"$ROOT/Tools/n64-bench/shim" -I"$APP_BRIDGE" -I"$OUT" "${FORMAT_INCLUDES[@]}" \
    -I"$AZAHAR/externals/zstd/lib" \
    -I"$AZAHAR/externals/libretro-common/libretro-common/include" \
    -I"$AZAHAR/externals/vulkan-headers/include" \
    "$HERE/3ds-bench.cpp" -o "$OUT/3ds-bench.o"
g++ "$OUT/N64VulkanFrontend.o" "$OUT/3ds-bench.o" "${LZFSE_OBJS[@]}" \
    -L"$CTR_IOS/lib" -l:libctr-core-host.so -Wl,-rpath,"$CTR_IOS/lib" \
    "$ZSTD_LIB" -l:libvulkan.so.1 -lstdc++ -lm -lpthread -ldl \
    -o "$OUT/3ds-bench"

echo "$OUT/3ds-bench"
